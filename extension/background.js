// ─── Privacy Mode ───

async function isPrivacyMode() {
  return new Promise(resolve => {
    chrome.storage.local.get(["privacyMode"], (r) => resolve(!!r.privacyMode));
  });
}

// ─── Cookie Management ───

function toNetscapeCookie(c) {
  const domain = c.domain.startsWith(".") ? c.domain : "." + c.domain;
  const includeSub = domain.startsWith(".");
  const path = c.path || "/";
  const secure = c.secure ? "TRUE" : "FALSE";
  const httpOnly = c.httpOnly ? "TRUE" : "FALSE";
  const expires = c.expirationDate ? Math.floor(c.expirationDate).toString() : "0";
  return `${domain}\t${includeSub ? "TRUE" : "FALSE"}\t${path}\t${secure}\t${expires}\t${c.name}\t${c.value}`;
}

async function extractYouTubeCookies() {
  const allCookies = [];
  for (const domain of YOUTUBE_DOMAINS) {
    try { allCookies.push(...await chrome.cookies.getAll({ domain })); } catch {}
  }
  const deduped = new Map();
  for (const c of allCookies) {
    const key = `${c.name}=${c.value}`;
    if (!deduped.has(key)) deduped.set(key, c);
  }
  const lines = [
    "# Netscape HTTP Cookie File",
    "# Generated by Transmux v5.0 Extension",
  ];
  for (const c of deduped.values()) lines.push(toNetscapeCookie(c));
  return lines.join("\n") + "\n";
}

async function sendCookies(backendUrl, jobId) {
  const cookiesTxt = await extractYouTubeCookies();
  const privacy = await isPrivacyMode();
  const res = await fetch(`${backendUrl}/api/cookies/${jobId}`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ cookies: cookiesTxt, privacyMode: privacy }),
  });
  const data = await res.json();
  if (!privacy) {
    chrome.storage.local.set({ lastSent: Date.now(), lastSentStr: new Date().toLocaleString() });
  }
  return data;
}

async function sendPendingCookies(backendUrl) {
  const cookiesTxt = await extractYouTubeCookies();
  const res = await fetch(`${backendUrl}/api/cookies/pending`, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify({ cookies: cookiesTxt }),
  });
  return res.json();
}


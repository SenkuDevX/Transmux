chrome.contextMenus.onClicked.addListener((info, tab) => {
  const url = info.linkUrl || info.srcUrl || tab?.url;
  if (!url) return;

  const actionMap = {
    "transmux-convert": { action: "convert" },
    "transmux-mp3": { action: "convert", outputFormat: "mp3" },
    "transmux-mp4": { action: "convert", outputFormat: "mp4" },
    "transmux-gif": { action: "convert", outputFormat: "gif" },
    "transmux-subtitles": { action: "convert", burnSubtitles: true, outputFormat: "mkv" },
    "transmux-queue": { action: "queue" },
  };

  const action = actionMap[info.menuItemId];
  if (action) {
    openTransmuxWith(url, action);
  }

  // Instant Remux: open with copy codec (lossless)
  if (info.menuItemId === "transmux-remux") {
    openTransmuxWith(url, { action: "convert", outputFormat: "mp4", videoCodec: "copy", audioCodec: "copy" });
  }

  // Compress: open with target size hint
  if (info.menuItemId === "transmux-compress") {
    openTransmuxWith(url, { action: "convert", targetSize: "25" });
  }

  // Open in Transmux
  if (info.menuItemId === "transmux-local-quick") {
    openTransmuxWith(url, {});
  }

  // Stealth Download
  if (info.menuItemId === "transmux-stealth") {
    const jobId = crypto.randomUUID();
    stealthDownload(BACKEND_DEFAULT, url, jobId, tab?.id).catch(() => {
      openTransmuxWith(url, {});
    });
  }
});

function openTransmuxWith(url, params) {
  const base = BACKEND_DEFAULT;
  const query = new URLSearchParams({ url: url, ...params });
  chrome.tabs.create({ url: `${base}?${query.toString()}` });
}

// ─── Port Connections (cookies + auth, merged) ───

chrome.runtime.onConnect.addListener((port) => {
  if (port.name === "transmux-cookies") {
    port.onMessage.addListener(async (request) => {
      if (request.type === "TRANSMUX_GET_COOKIES") {
        try {
          const data = await sendCookies(request.backendUrl, request.jobId);
          port.postMessage({ success: true, data });
        } catch (err) {
          port.postMessage({ success: false, error: err.message });
        }
      }
      if (request.type === "TRANSMUX_SEND_PENDING_COOKIES") {
        try {
          const data = await sendPendingCookies(request.backendUrl);
          port.postMessage({ success: true, data });
        } catch (err) {
          port.postMessage({ success: false, error: err.message });
        }
      }
    });
  } else if (port.name === "transmux-auth") {
    port.onMessage.addListener((msg) => {
      if (msg.type === "AUTH_LOGIN") {
        chrome.storage.local.set({ authState: "authenticated", authUser: msg.user, authToken: msg.token });
        port.postMessage({ success: true });
      }
      if (msg.type === "AUTH_LOGOUT") {
        chrome.storage.local.remove(["authState", "authUser", "authToken"]);
        port.postMessage({ success: true });
      }
      if (msg.type === "AUTH_CHECK") {
        chrome.storage.local.get(["authState", "authUser", "authToken"], (r) => {
          port.postMessage({ state: r.authState, user: r.authUser, token: r.authToken });
        });
      }
    });
  }
});

// ─── Tab Media Detection ───

async function detectMediaInTab(tabId) {
  try {
    const results = await chrome.scripting.executeScript({
      target: { tabId },
      func: () => {
        const media = [];
        document.querySelectorAll("video").forEach(v => {
          if (v.src && v.src.startsWith("http")) media.push({ type: "video", src: v.src, duration: v.duration });
          v.querySelectorAll("source").forEach(s => {
            if (s.src && s.src.startsWith("http")) media.push({ type: "video", src: s.src });
          });
        });
        document.querySelectorAll("audio").forEach(a => {
          if (a.src && a.src.startsWith("http")) media.push({ type: "audio", src: a.src, duration: a.duration });
        });
        return media;
      },
    });
    return results?.[0]?.result || [];
  } catch { return []; }
}

// ─── Content Script Messages ───

chrome.runtime.onMessage.addListener((message, sender, sendResponse) => {
  if (message.type === "TRANSMUX_DETECT_SITE") {
    const tab = sender.tab;
    const url = tab?.url || "";
    const match = Object.entries(SUPPORTED_SITES).find(([domain]) => url.includes(domain));
    sendResponse({ detected: !!match, site: match ? match[1] : null, url });
  }
  if (message.type === "TRANSMUX_NOTIFY") {
    chrome.notifications.create({
      type: "basic",
      iconUrl: "icon.svg",
      title: message.title || "Transmux",
      message: message.message || "",
    });
  }
  if (message.type === "TRANSMUX_STEALTH_COMPLETE") {
    chrome.notifications.create({
      type: "basic",
      iconUrl: "icon.svg",
      title: "Stealth Download Complete",
      message: `Media from ${message.url?.slice(0, 50)}... downloaded via browser`,
    });
  }
  if (message.type === "TRANSMUX_AUTH_STATE") {
    // Store auth state from Clerk
    chrome.storage.local.set({ authState: message.authState, authUser: message.user });
    sendResponse({ stored: true });
  }
  if (message.type === "TRANSMUX_GET_AUTH") {
    chrome.storage.local.get(["authState", "authUser"], (r) => {
      sendResponse({ state: r.authState, user: r.authUser });
    });
    return true;
  }
});

// ─── Periodic Cookie Auto-Refresh ───

chrome.alarms.create("transmux-cookie-refresh", { periodInMinutes: 30 });

chrome.alarms.onAlarm.addListener(async (alarm) => {
  if (alarm.name === "transmux-cookie-refresh") {
    const cookiesTxt = await extractYouTubeCookies();
    const count = (cookiesTxt.match(/\n/g) || []).length - 2;
    chrome.storage.local.set({ cookieCount: Math.max(0, count), lastRefresh: Date.now() });
  }
});

